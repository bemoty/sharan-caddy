#!/usr/bin/env bash
set -euo pipefail

BIN="$1"
OUTDIR="$2"

PKG_NAME="sharan-caddy"
PKG_SUMMARY="Caddy web server built for use with Sharan"

RAW="$(mktemp -d)"
trap 'rm -rf "$RAW"' EXIT

mkdir -p "$OUTDIR"
"$BIN" manpage --directory "$RAW"

for f in "$RAW"/*.8; do
  dst="$OUTDIR/sharan-$(basename "$f")"
  sed -E \
    -e "s|^\.TH \"Caddy\" \"8\" \"[^\"]*\" \"Auto generated by spf13/cobra\" \"\"\$|.TH \"${PKG_NAME}\" \"8\" \"\" \"Auto generated by spf13/cobra\" \"\"|" \
    -e "s|^[0-9]{1,2}-[A-Za-z]{3}-[0-9]{4} Auto generated by spf13/cobra\$|Auto generated by spf13/cobra|" \
    -e "s|\\\\fBcaddy|\\\\fB${PKG_NAME}|g" \
    -e "/^\.SH NAME\$/{n; s|^caddy|${PKG_NAME}|; s|^${PKG_NAME} -\$|${PKG_NAME} - ${PKG_SUMMARY}|}" \
    "$f" > "$dst"
done

gzip -9n "$OUTDIR"/*.8
